CREATE TABLE IF NOT EXISTS orders (
    o_id        INT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    user_id     UUID REFERENCES users(u_id) ON DELETE SET NULL,
    location    TEXT NOT NULL,
	phone_number VARCHAR(20) NOT NULL,
	status      VARCHAR(25) NOT NULL DEFAULT 'Processing' CHECK (status IN ('Processing', 'Shipped', 'Delivered', 'Cancelled')),
    total_price NUMERIC(12, 2) NOT NULL CHECK (total_price >= 0),
    method      VARCHAR(20) NOT NULL CHECK (method IN ('visa', 'cash')),
    courier_id  UUID REFERENCES users(u_id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ    DEFAULT NOW(),
    shipped_at  TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ
);